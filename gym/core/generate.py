"""Templates -> instances.

  templates/<layer>/<id>/template.yaml    (+ chaos.yaml etc., + an optional hand-written
                                           reference_solution.md)
      -> scenarios/<id>/spec.yaml           resolved, validated, hashed
         scenarios/<id>/reference_solution.md
         scenarios/<id>/<other files>       copied unchanged
  and scenarios/CATALOG.md

Resolving fills in templates/defaults.yaml (forbidden actions, invariants, validation timings,
tools, budget) and derives verifier.durability from the fault when the template does not set it.

Two hashes:
  validation_hash  what a live validation run depends on: fault, checks, invariants, durability,
                   reference fix, validation timings, extra files. Validation status is keyed on it, so
                   rewording a prompt or an explanation does not throw away validation runs.
  content_hash     everything that decides how a scenario behaves and is graded: the above plus
                   prompts, ground truth, forbidden actions, budget and tools. Benchmark results
                   and suites are keyed on it.
"""
from __future__ import annotations

import hashlib
import json
import pathlib

import yaml

from .schema import Defaults, Instance, Template

REPO = pathlib.Path(__file__).resolve().parents[2]
TEMPLATES = REPO / "templates"
SCENARIOS = REPO / "scenarios"
TEMPLATE_FILE = "template.yaml"
REFERENCE_FILE = "reference_solution.md"
HEADER = ("# GENERATED by scripts/generate.py from templates/{layer}/{id}/ -- do not edit.\n"
          "# Edit the template and run: python scripts/generate.py\n")


class Dumper(yaml.SafeDumper):
    pass


def _str(dumper, data):
    return dumper.represent_scalar("tag:yaml.org,2002:str", data, style="|" if "\n" in data else None)


Dumper.add_representer(str, _str)


def dump(data):
    return yaml.dump(data, Dumper=Dumper, sort_keys=False, width=110, allow_unicode=True)


# ----------------------------------------------------------------- loading
def load_defaults():
    return Defaults.model_validate(yaml.safe_load((TEMPLATES / "defaults.yaml").read_text()))


def template_dirs():
    return sorted(p.parent for p in TEMPLATES.glob(f"*/*/{TEMPLATE_FILE}"))


def load_template(tdir):
    raw = yaml.safe_load((tdir / TEMPLATE_FILE).read_text())
    model = Template.model_validate(raw)
    if tdir.name != model.id:
        raise ValueError(f"{tdir}: folder name does not match id {model.id!r}")
    if tdir.parent.name != model.tags.layer:
        raise ValueError(f"{tdir}: folder is under {tdir.parent.name}/ but tags.layer is {model.tags.layer!r}")
    return raw, model


def extra_files(tdir):
    """Files the instance needs besides spec.yaml (e.g. chaos.yaml), as {name: text}."""
    return {p.name: p.read_text() for p in sorted(tdir.iterdir())
            if p.is_file() and p.name not in (TEMPLATE_FILE, REFERENCE_FILE)}


# --------------------------------------------------------------- resolving
def _sha(payload):
    blob = json.dumps(payload, sort_keys=True, separators=(",", ":"), ensure_ascii=False)
    return "sha256:" + hashlib.sha256(blob.encode()).hexdigest()


def validation_hash(inst, files):
    v = inst["verifier"]
    return _sha({
        "fault": inst["fault"], "checks": v["checks"], "invariants": v["invariants"], "durability": v["durability"],
        "commands": inst["reference"]["commands"], "validation": inst["validation"],
        "files": {n: hashlib.sha256(t.encode()).hexdigest() for n, t in sorted(files.items())},
    })


def content_hash(inst, files):
    return _sha({
        "validation_hash": validation_hash(inst, files), "task": inst["task"],
        "ground_truth": inst["ground_truth"], "forbidden": inst["verifier"]["forbidden"],
        "budget": inst["budget"], "tools": inst["tools"],
    })


# Durability: after the fix passes, these workloads are restarted and the checks must pass again,
# so a fix that only patched live state (and is lost on the next restart) fails.
NO_DURABILITY = ("runtime.exec", "app.flag", "chaos.mesh")   # a restart would clear the fault itself


def derive_durability(fault):
    """Restart targets for a fault, unless the template sets verifier.durability itself:
    the workloads it patched, the readers it restarted and the pods it recreated. Decoy (noise)
    steps and mechanisms whose fault a restart clears contribute nothing."""
    out = []

    def add(target, namespace=None):
        entry = {"restart": target, **({"namespace": namespace} if namespace else {})}
        if entry not in out:
            out.append(entry)
    for step in fault["steps"]:
        mech = step["mechanism"]
        if step.get("noise") or mech in NO_DURABILITY:
            continue
        ns = step.get("namespace")
        if mech == "k8s.workload_patch":
            add(f"{step.get('kind', 'deployment')}/{step['target']}", ns)
        elif mech == "k8s.memory_limit":
            add(f"deployment/{step['target_deployment']}")
        elif mech == "app.flag_source_config":
            add("deployment/flagd")
        for target in step.get("restart_after", []):
            add(target, ns)
        for selector in step.get("recreate_pods_after", []):
            add(selector)
    return out


def resolve_verifier(verifier, fault, defaults):
    extra = [f for f in verifier.get("forbidden_extra", []) if f not in defaults.forbidden]
    durability = verifier.get("durability")
    return {"checks": verifier["checks"],
            "invariants": list(defaults.invariants if verifier.get("invariants") is None else verifier["invariants"]),
            "durability": derive_durability(fault) if durability is None else durability,
            "forbidden": list(defaults.forbidden) + extra}


def resolve(raw, defaults, files):
    """The instance dict: the template's own keys in its order, defaults filled in, hash added."""
    inst = json.loads(json.dumps(raw))
    inst["verifier"] = resolve_verifier(inst["verifier"], inst["fault"], defaults)
    validation = {**defaults.validation.model_dump(),
                  **{k: v for k, v in (inst.pop("validation", None) or {}).items() if v is not None}}
    resolved = {"tools": inst.get("tools") or list(defaults.tools),
                "budget": inst.get("budget") or defaults.budget.model_dump()}
    out = {}
    for key, value in inst.items():
        if key in resolved:
            continue
        out[key] = value
        if key == "version":
            out["instance_of"] = {"template": raw["id"], "version": raw.get("version", 1), "params": {}}
            out["content_hash"] = out["validation_hash"] = None
        if key == "bench_eligible":   # keep the resolved defaults next to the other top-level settings
            out.update(resolved)
        if key == "reference":
            out["validation"] = validation
    out.update({k: v for k, v in resolved.items() if k not in out})
    out["validation_hash"] = validation_hash(out, files)
    out["content_hash"] = content_hash(out, files)
    Instance.model_validate(out)
    return out


# ------------------------------------------------------ reference solution
def reference_markdown(inst):
    ref, gt = inst["reference"], inst["ground_truth"]
    hard = bool(ref.get("traps"))
    lines = [f"# Reference solution: {inst['id']}", "", f"**{inst['title']}**", "",
             f"**Root cause:** {gt['explanation']}", "",
             "## How a careful SRE finds it" if hard else "## How to find it", ""]
    lines += [f"{i}. {step}" for i, step in enumerate(gt["evidence"], 1)]
    if hard:
        lines += ["", "## Traps (why this is hard)", ""] + [f"- {t}" for t in ref["traps"]]
    if gt.get("red_herrings"):
        lines += ["", "## Noise in this scenario (not the cause)", ""] + [f"- {n}" for n in gt["red_herrings"]]
    lines += ["", "## Fix", "", "```bash", *ref["commands"], "```", "", "## Confirm", "",
              f"`python verifiers/verify.py scenarios/{inst['id']}` passes.", ""]
    return "\n".join(lines)


def answer_key(inst):
    """The judge's answer key: the ground truth as plain text."""
    gt = inst["ground_truth"]
    lines = ["ROOT CAUSE(S). A correct report names every one of these:"]
    for i, rc in enumerate(gt["root_causes"], 1):
        where = f" (namespace {rc['namespace']})" if rc.get("namespace") else " (cluster-scoped)"
        if rc["component"].endswith("/$workers"):
            where = " (every worker node)"
        lines.append(f"{i}. {rc['component']}{where}: {rc['what']}")
    lines += ["", "HOW IT CAUSES THE SYMPTOM:", gt["explanation"], "", "EVIDENCE AN ENGINEER CAN SEE:"]
    lines += [f"- {e}" for e in gt["evidence"]]
    if gt.get("red_herrings"):
        lines += ["", "NOISE (observed, but NOT the cause):"] + [f"- {r}" for r in gt["red_herrings"]]
    lines += ["", "REFERENCE FIX:"] + [f"  {c}" for c in inst["reference"]["commands"]]
    return "\n".join(lines)


# ---------------------------------------------------------------- building
def build(tdir, defaults):
    """{relative file name: text} for one instance folder."""
    raw, model = load_template(tdir)
    files = extra_files(tdir)
    inst = resolve(raw, defaults, files)
    hand_written = tdir / REFERENCE_FILE
    reference = hand_written.read_text() if hand_written.exists() else reference_markdown(inst)
    out = {"spec.yaml": HEADER.format(layer=model.tags.layer, id=model.id) + dump(inst), REFERENCE_FILE: reference}
    out.update(files)
    return model.id, out


def build_all():
    defaults = load_defaults()
    built, mechanisms = {}, {}
    for tdir in template_dirs():
        sid, files = build(tdir, defaults)
        if sid in built:
            raise ValueError(f"duplicate scenario id {sid}")
        built[sid] = files
        mech = yaml.safe_load(files["spec.yaml"])["mechanism"]
        mechanisms.setdefault(mech, []).append(sid)
    dups = {m: ids for m, ids in mechanisms.items() if len(ids) > 1}
    if dups:
        raise ValueError(f"mechanism keys must be unique (one root-cause class per scenario): {dups}")
    return built


def stale(built):
    """Paths under scenarios/ that differ from what the templates generate (or should not exist)."""
    problems = []
    for sid, files in built.items():
        for name, text in files.items():
            p = SCENARIOS / sid / name
            if not p.exists() or p.read_text() != text:
                problems.append(str(p.relative_to(REPO)))
    for d in sorted(p for p in SCENARIOS.iterdir() if p.is_dir()):
        if d.name not in built:
            problems.append(f"{d.relative_to(REPO)} (no template)")
        else:
            for f in d.iterdir():
                if f.name not in built[d.name]:
                    problems.append(f"{f.relative_to(REPO)} (not generated)")
    return problems


def write(built):
    for sid, files in built.items():
        d = SCENARIOS / sid
        d.mkdir(parents=True, exist_ok=True)
        for name, text in files.items():
            (d / name).write_text(text)
        for f in d.iterdir():
            if f.name not in files:
                f.unlink()
    for d in sorted(p for p in SCENARIOS.iterdir() if p.is_dir()):
        if d.name not in built:
            raise ValueError(f"{d.relative_to(REPO)} has no template; delete it or add templates/*/{d.name}/")


# ------------------------------------------------------------------ catalog
def latest_records():
    path = REPO / "results" / "validation.jsonl"
    recs = {}
    if path.exists():
        for line in path.read_text().splitlines():
            try:
                rec = json.loads(line)
            except ValueError:
                continue
            recs[rec["id"]] = rec
    return recs


def catalog_markdown(built):
    specs = [yaml.safe_load(files["spec.yaml"]) for files in built.values()]
    recs = latest_records()
    layers = {}
    for s in specs:
        layers.setdefault(s["tags"]["layer"], []).append(s)
    validated = sum(1 for s in specs if recs.get(s["id"], {}).get("verdict") == "VALIDATED")
    summary = ["| layer | scenarios | hard tier | bench-eligible | validated | median detect | median recover |",
               "|---|---|---|---|---|---|---|"]
    for layer in sorted(layers):
        group = layers[layer]
        ok = [recs[s["id"]] for s in group if recs.get(s["id"], {}).get("verdict") == "VALIDATED"]

        def med(key):
            vals = sorted(r["timings"][key] for r in ok if key in r.get("timings", {}))
            return f"{vals[len(vals) // 2]}s" if vals else "-"
        summary.append(f"| {layer} | {len(group)} | {sum(s['split'] == 'hard' for s in group)} | "
                       f"{sum(s.get('bench_eligible', True) for s in group)} | {len(ok)} | "
                       f"{med('detect_s')} | {med('recover_s')} |")
    axes = []
    for axis in ("symptom", "fix_type", "drivers", "injector"):
        counts = {}
        for s in specs:
            values = s["tags"].get(axis) or []
            for v in (values if isinstance(values, list) else [values]):
                counts[v] = counts.get(v, 0) + 1
        axes.append(f"- **{axis}**: " + ", ".join(f"{k} {n}" for k, n in sorted(counts.items(), key=lambda x: -x[1])))
    lines = ["# Scenario catalog", "",
             "Generated by `scripts/generate.py` from `templates/`. Do not edit.", "",
             f"{len(specs)} scenarios, each a distinct root-cause mechanism "
             f"({validated} validated end to end on the live cluster).", "",
             *summary, "",
             "Detect = time from injection until the verifier fails; recover = time from running the reference "
             "solution until it passes again. Validation verdicts here are the latest run per scenario.", "",
             "Tags (see `templates/taxonomy.yaml`):", "", *axes, "",
             "Uniqueness rule: a scenario counts only if its root-cause mechanism differs from every other one. "
             "Changing only numbers (memory size, latency, percentages), names or random seeds makes a variant, "
             "not a new scenario, so variants are not listed here.", "",
             "Validation = baseline healthy -> inject -> verifier FAIL -> still FAIL for a do-nothing agent "
             "-> reference solution -> verifier PASS -> exact restore (see `scripts/validate_scenario.py`).", "",
             "| id | layer | tier | symptom | fix | mechanism | title | bench | validation |",
             "|---|---|---|---|---|---|---|---|---|"]
    for layer in sorted(layers):
        for s in sorted(layers[layer], key=lambda x: x["id"]):
            t = s["tags"]
            lines.append(f"| `{s['id']}` | {layer} | {s['split']} | {t['symptom']} | {', '.join(t['fix_type'])} | "
                         f"`{s['mechanism']}` | {s['title']} | {'yes' if s.get('bench_eligible', True) else 'no'} | "
                         f"{recs.get(s['id'], {}).get('verdict', 'not run')} |")
    lines.append("")
    return "\n".join(lines)
