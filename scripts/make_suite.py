"""Freeze a suite: a seeded, tag-balanced selection of validated instances.

  python scripts/make_suite.py --name bench-v1-test --visibility private --n 40 --clean --cap fix_type=flag:4
  python scripts/make_suite.py --name bench-v1-dev --n 20 --exclude bench-v1-test --cap fix_type=flag:4
  python scripts/make_suite.py --name hard-v1 --split hard --n 12
  python scripts/make_suite.py --name lite --n 10 --clean --fastest --exclude bench-v1-test
  python scripts/make_suite.py --check        every suite still matches the current instances (CI)
  python scripts/make_suite.py --refreeze hard-v1   next version: same members at their current hashes

Candidates are bench-eligible instances whose current version is validated, including at least one
passing long-hold run (scripts/validate_scenario.py --long-hold); with --clean, no failed validation
run at all. The candidates are grouped by --balance (default: layer) and each group gets its share of the n slots in proportion to its size (largest remainder; at least one each
when n allows). Within a group, instances are taken in seeded random order, preferring ones whose
symptom and fix types the suite does not have yet; --fastest takes the ones with the shortest
validation timings instead. --cap AXIS=VALUE:N admits at most N members carrying that tag value; slots
a capped group cannot fill go to the other groups in proportion to their sizes.

Suites are frozen: writing a different suite over an existing name and version is refused; bump
--version instead. Public suites are written to suites/, private ones to private/suites/
(gym/core/suites.py).
"""
import argparse
import collections
import pathlib
import random
import sys

import yaml

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))

from gym.core import generate, status, suites  # noqa: E402
from gym.core.schema import Suite  # noqa: E402

HEADER = ("# GENERATED by scripts/make_suite.py. Frozen: do not edit; make a new version instead.\n"
          "# {summary}\n")


def tag_values(spec, axis):
    v = spec["tags"].get(axis) or []
    return v if isinstance(v, list) else [v]


def episode_seconds(spec, st):
    """Rough cluster time of one episode besides the agent: detection, recovery, hold, durability, reset."""
    t = st.timings
    return (t.get("detect_s", 0) + t.get("recover_s", 0) + t.get("durable_s", 0) + t.get("restore_s", 0)
            + spec["validation"]["hold_s"])


def candidates(insts, records, split, clean, exclude):
    out = []
    for sid, (spec, _) in sorted(insts.items()):
        if not spec.get("bench_eligible", True) or sid in exclude:
            continue
        if spec["task"].get("kind") == "diagnose":   # suites are graded in fix mode, which never plays these
            continue
        if split != "all" and spec["split"] != split:
            continue
        st = status.of_spec(spec, records)
        if st.status != "validated" or (clean and st.failures) or not st.long_holds:
            continue
        out.append({"id": sid, "spec": spec, "status": st, "seconds": episode_seconds(spec, st)})
    return out


def quotas(sizes, n):
    """Slots per group, proportional to group size (largest remainder), at least one each when n allows."""
    total, order = sum(sizes.values()), sorted(sizes)
    exact = {g: n * sizes[g] / total for g in order}
    quota = {g: int(exact[g]) for g in order}
    if n >= len(order):
        for g in order:
            quota[g] = max(1, quota[g])
    for g in sorted(order, key=lambda g: (-(exact[g] - int(exact[g])), g)):
        if sum(quota.values()) >= n:
            break
        if quota[g] < sizes[g]:
            quota[g] += 1
    while sum(quota.values()) > n:   # the 'at least one' rule can overshoot
        g = max(order, key=lambda g: (quota[g] - exact[g], g))
        quota[g] -= 1
    return quota


def select(pool, n, balance, caps, seed, fastest):
    """The chosen candidates and the quota per group."""
    rng = random.Random(seed)
    groups = collections.defaultdict(list)
    for c in pool:
        values = tag_values(c["spec"], balance)
        if len(values) != 1:
            sys.exit(f"--balance needs a single-valued tag axis (layer, symptom, injector); {balance} is not")
        groups[values[0]].append(c)
    for g in groups.values():
        rng.shuffle(g)
        if fastest:
            g.sort(key=lambda c: c["seconds"])   # stable: equal times keep the seeded order
    n = min(n, len(pool))
    quota = quotas({g: len(v) for g, v in groups.items()}, n)
    picked, seen = [], collections.Counter()   # seen: (axis, value) -> members carrying it
    taken = collections.Counter()               # group -> members taken from it

    def allowed(c):
        return all(seen[key] < limit for key, limit in caps.items() if key[1] in tag_values(c["spec"], key[0]))

    def novelty(c):   # lower = adds a symptom / fix type the suite does not have yet
        return sum(seen[(axis, v)] for axis in ("symptom", "fix_type") for v in tag_values(c["spec"], axis))

    def take(g):
        options = [c for c in groups[g] if allowed(c)]
        if not options:
            return False
        c = options[0] if fastest else min(options, key=novelty)   # min() keeps the first of equals
        groups[g].remove(c)
        picked.append(c)
        taken[g] += 1
        for axis in {"symptom", "fix_type"} | {a for a, _ in caps}:
            for v in tag_values(c["spec"], axis):
                seen[(axis, v)] += 1
        return True

    short = 0
    for g in sorted(quota):
        for _ in range(quota[g]):
            if not take(g):
                short += 1
    sizes = {g: taken[g] + len(groups[g]) for g in groups}
    while short:   # unfilled slots go to the open group furthest below its share among the open groups
        open_groups = [g for g in groups if any(allowed(c) for c in groups[g])]
        if not open_groups:
            break
        seats = sum(taken[g] for g in open_groups) + short
        total = sum(sizes[g] for g in open_groups)
        take(max(open_groups, key=lambda g: (seats * sizes[g] / total - taken[g], g)))
        short -= 1
    return picked, quota


def parse_caps(items):
    caps = {}
    for item in items or []:
        try:
            key, limit = item.rsplit(":", 1)
            axis, value = key.split("=", 1)
            caps[(axis, value)] = int(limit)
        except ValueError:
            sys.exit(f"--cap {item!r}: expected AXIS=VALUE:N, e.g. fix_type=flag:4")
    return caps


def render(suite, picked, balance, summary):
    head = suite.model_dump(exclude={"instances"})
    lines = [HEADER.format(summary=summary).rstrip("\n"), generate.dump(head).rstrip("\n"), "instances:"]
    for c in sorted(picked, key=lambda c: (tag_values(c["spec"], balance)[0], c["id"])):
        t = c["spec"]["tags"]
        note = " / ".join([t["layer"], ",".join(t["fix_type"])] + ([",".join(t["drivers"])] if t.get("drivers") else []))
        lines.append(f'- {{id: {c["id"]}, hash: "{c["spec"]["content_hash"]}"}}   # {note}')
    return "\n".join(lines) + "\n"


def check():
    insts, records, bad = suites.instances(), status.load_records(), 0
    paths = suites.all_suites()
    for path in paths:
        suite = suites.load(path)
        problems = suites.verify(suite, insts, records)
        bad += bool(problems)
        print(f"{'FAIL' if problems else 'ok  '} {suite.name} v{suite.version} ({suite.visibility}, "
              f"{len(suite.instances)} instances) {path}")
        for p in problems:
            print(f"     - {p}")
    if not paths:
        print("no suites found")
    sys.exit(1 if bad else 0)


def refreeze(ref, dry_run=False):
    """The next version of a suite with the same members at their current hashes: for when members changed
    (a fixed scenario) but the selection should not. Every member must still qualify for the suite."""
    path, old = suites.find(ref), suites.load(ref)
    insts, records = suites.instances(), status.load_records()
    missing = [m.id for m in old.instances if m.id not in insts]
    if missing:
        sys.exit(f"members no longer exist: {missing}; make a new selection instead")
    picked = [{"id": m.id, "spec": insts[m.id][0], "status": status.of_spec(insts[m.id][0], records)}
              for m in old.instances]
    changed = sorted(c["id"] for c, m in zip(picked, old.instances) if c["spec"]["content_hash"] != m.hash)
    if not changed:
        sys.exit(f"{old.name} v{old.version} still matches every member; nothing to refreeze")
    clean = old.selection.get("clean")
    unfit = [f"{c['id']}: {c['status'].summary()}" for c in picked
             if c["status"].status != "validated" or not c["status"].long_holds or (clean and c["status"].failures)]
    if unfit:
        sys.exit("these members do not qualify any more (validate them, or make a new selection):\n  "
                 + "\n  ".join(unfit))
    suite = Suite.model_validate({
        **old.model_dump(exclude={"version", "selection", "instances"}), "version": old.version + 1,
        "selection": {**old.selection, "refrozen_from": old.version, "changed": changed},
        "instances": [{"id": c["id"], "hash": c["spec"]["content_hash"]} for c in picked]})
    balance = old.selection.get("balance", "layer")
    by_group = collections.Counter(tag_values(c["spec"], balance)[0] for c in picked)
    summary = (f"v{old.version} members at their current hashes (changed: {', '.join(changed)}); by {balance}: "
               + ", ".join(f"{g} {by_group[g]}" for g in sorted(by_group)))
    text = render(suite, picked, balance, summary)
    if dry_run:
        print(text)
        return
    path.write_text(text)
    print(f"wrote {path}: {suite.name} v{suite.version}; {summary}")


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--check", action="store_true", help="verify every suite against the current instances")
    p.add_argument("--refreeze", metavar="SUITE",
                   help="next version of this suite: same members, current hashes (after members were fixed)")
    p.add_argument("--name")
    p.add_argument("--version", type=int, default=1)
    p.add_argument("--n", type=int, help="how many instances")
    p.add_argument("--seed", type=int, default=1, help="same seed and inputs = same suite")
    p.add_argument("--split", default="train", choices=["train", "hard", "all"],
                   help="which tier to draw from (default: train, the standard scenarios)")
    p.add_argument("--visibility", default="public", choices=["public", "private"])
    p.add_argument("--hint-level", default="page", choices=["page", "ticket", "hinted"],
                   help="the prompt every model gets on this suite (default: page, symptoms only)")
    p.add_argument("--balance", default="layer", help="tag axis to stratify by (default: layer)")
    p.add_argument("--cap", action="append", metavar="AXIS=VALUE:N", help="at most N members with this tag value")
    p.add_argument("--clean", action="store_true", help="only instances with no failed validation run (5/5)")
    p.add_argument("--fastest", action="store_true", help="prefer the shortest validation timings in each group")
    p.add_argument("--exclude", action="append", default=[], metavar="SUITE",
                   help="leave out the members of this suite (name or path; repeatable)")
    p.add_argument("--description", default="")
    p.add_argument("--dry-run", action="store_true", help="print the selection, write nothing")
    a = p.parse_args()
    if a.check:
        return check()
    if a.refreeze:
        return refreeze(a.refreeze, a.dry_run)
    if not a.name or not a.n:
        p.error("--name and --n are required (or use --check)")

    insts, records = suites.instances(), status.load_records()
    exclude = sorted({m.id for ref in a.exclude for m in suites.load(ref).instances})
    pool = candidates(insts, records, a.split, a.clean, set(exclude))
    if not pool:
        sys.exit("no candidates: nothing bench-eligible and validated matches")
    caps = parse_caps(a.cap)
    picked, quota = select(pool, a.n, a.balance, caps, a.seed, a.fastest)
    if len(picked) < a.n:
        print(f"note: only {len(picked)} of the {a.n} requested could be chosen (pool {len(pool)}, caps {a.cap})")

    suite = Suite.model_validate({
        "name": a.name, "version": a.version, "visibility": a.visibility, "hint_level": a.hint_level,
        "description": a.description,
        "selection": {"seed": a.seed, "n": a.n, "split": a.split, "balance": a.balance,
                      "caps": {f"{axis}={v}": n for (axis, v), n in caps.items()}, "clean": a.clean,
                      "fastest": a.fastest, "exclude": [suites.load(r).name for r in a.exclude],
                      "candidates": len(pool)},
        "instances": [{"id": c["id"], "hash": c["spec"]["content_hash"]} for c in picked]})
    by_group = collections.Counter(tag_values(c["spec"], a.balance)[0] for c in picked)
    summary = (f"{len(picked)} of {len(pool)} candidates; by {a.balance}: "
               + ", ".join(f"{g} {by_group[g]}" for g in sorted(by_group)))
    text = render(suite, picked, a.balance, summary)
    if a.dry_run:
        print(text)
        print(f"quota by {a.balance}: {dict(sorted(quota.items()))}")
        return

    out_dir = suites.SUITES if a.visibility == "public" else suites.private_root() / "suites"
    out = out_dir / f"{a.name}.yaml"
    if out.exists():
        old = Suite.model_validate(yaml.safe_load(out.read_text()))
        if old.version == a.version and old != suite:
            sys.exit(f"{out} already holds version {old.version} with different content; suites are frozen. "
                     f"Use --version {old.version + 1}.")
        if old.version > a.version:
            sys.exit(f"{out} holds a newer version ({old.version})")
    out_dir.mkdir(parents=True, exist_ok=True)
    out.write_text(text)
    print(f"wrote {out}: {summary}")


if __name__ == "__main__":
    main()
