"""Snapshot the healthy live world into tests/fixtures/world.json for the offline tests.

usage: python scripts/dump_world_fixture.py      (cluster healthy, no fault injected)

Read-only: it only runs `kubectl get` and reads flagd's live flag file. The offline tests
(tests/fakes.py) load this file as their in-memory cluster, so faults are injected and reverted
against the real object shapes (container names, env vars, ports, selectors) instead of
hand-written stand-ins.

Not captured: Secrets (credentials must not end up in git), kube-system ConfigMaps other than
CoreDNS and kube-proxy (cluster certificates and kubeadm settings), webhook CA bundles, Grafana
dashboard ConfigMaps (large and never touched by a fault), and pod status. Pods are kept only as
name, labels and container ports, which is what the fault code reads from them.
"""
import json
import pathlib
import sys

REPO = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))

from gym import kube, undo  # noqa: E402
from gym.faults import flags  # noqa: E402

OUT = REPO / "tests" / "fixtures" / "world.json"

NAMESPACED = {
    kube.APP_NS: ["deployments.apps", "daemonsets.apps", "statefulsets.apps", "services", "configmaps",
                  "networkpolicies.networking.k8s.io", "resourcequotas", "limitranges", "serviceaccounts"],
    "kube-system": ["deployments.apps", "daemonsets.apps", "configmaps"],
    kube.GYM_NS: ["deployments.apps"],
}
CLUSTER = ["nodes", "namespaces", "validatingwebhookconfigurations.admissionregistration.k8s.io",
           "mutatingwebhookconfigurations.admissionregistration.k8s.io"]
KUBE_SYSTEM_CONFIGMAPS = {"coredns", "kube-proxy"}


def keep(obj):
    meta = obj["metadata"]
    if obj["kind"] == "ConfigMap":
        if meta["name"].startswith("grafana-dashboard-") or meta["name"] == "kube-root-ca.crt":
            return False
        if meta.get("namespace") == "kube-system" and meta["name"] not in KUBE_SYSTEM_CONFIGMAPS:
            return False
    if meta.get("ownerReferences") and obj["kind"] not in ("Pod",):
        return False  # controller-made (ReplicaSets, Jobs' pods, ...)
    return True


def clean(obj):
    o = undo.clean_manifest(obj)
    if o["kind"] == "Node":
        o["spec"].pop("podCIDR", None)
        o["spec"].pop("podCIDRs", None)
        o["spec"].pop("providerID", None)
    for hook in o.get("webhooks", []):
        hook.get("clientConfig", {}).pop("caBundle", None)
    return o


def slim_pod(pod):
    return {"apiVersion": "v1", "kind": "Pod",
            "metadata": {"name": pod["metadata"]["name"], "namespace": pod["metadata"]["namespace"],
                         "labels": pod["metadata"].get("labels", {})},
            "spec": {"containers": [{"name": c["name"], "ports": c.get("ports", [])}
                                    for c in pod["spec"]["containers"]]}}


def main():
    if (REPO / ".gym_state").exists() and any((REPO / ".gym_state").glob("**/*.json")):
        sys.exit("a fault is injected (.gym_state/ is not empty); revert it before taking the snapshot")
    objects = []
    for ns, kinds in NAMESPACED.items():
        for kind in kinds:
            objects += [clean(o) for o in kube.items(kind, namespace=ns) if keep(o)]
    for kind in CLUSTER:
        objects += [clean(o) for o in kube.items(kind, namespace=None) if keep(o)]
    objects += [slim_pod(p) for p in kube.items("pods", namespace=kube.APP_NS)
                if p.get("status", {}).get("phase") == "Running"]
    fixture = {
        "comment": "Generated by scripts/dump_world_fixture.py from a healthy cluster. Do not edit by hand.",
        "objects": sorted(objects, key=lambda o: (o["kind"], o["metadata"].get("namespace") or "",
                                                  o["metadata"]["name"])),
        "flagd_live_file": flags.read_config(),
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(fixture, indent=1, sort_keys=True) + "\n")
    counts = {}
    for o in objects:
        counts[o["kind"]] = counts.get(o["kind"], 0) + 1
    print(f"wrote {OUT.relative_to(REPO)}: {len(objects)} objects {counts}")


if __name__ == "__main__":
    main()
